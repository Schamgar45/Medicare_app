// Normalise les clés pour la recherche : apostrophes/guillemets courbes -> droites,
// afin qu'une chaîne saisie avec des apostrophes courbes trouve une entrée droite (et vice versa).
function normalizeKey(s: string): string {
  return s
    .replace(/\u2019/g, "'") // right single quotation mark -> straight apostrophe
    .replace(/\u2018/g, "'") // left single quotation mark -> straight apostrophe
    .replace(/\u201c/g, '"') // left double quotation mark -> straight quote
    .replace(/\u201d/g, '"'); // right double quotation mark -> straight quote
}

// Maps de recherche normalisées (construites une fois au chargement du module).
const normalizedTranslations: Record<string, string> = {};
for (const [k, v] of Object.entries(translations)) {
  normalizedTranslations[normalizeKey(k)] = v;
}
const normalizedAdditional: Record<string, string> = {};
for (const [k, v] of Object.entries(additionalTranslations)) {
  normalizedAdditional[normalizeKey(k)] = v;
}

let currentLanguage: Language = (() => {
  try {
    return localStorage.getItem(LANGUAGE_KEY) === 'en' ? 'en' : 'fr';
  } catch {
    return 'fr';
  }
})();

export function t(text: string): string {
  if (currentLanguage === 'fr') return text;
  const key = normalizeKey(text);
  return normalizedTranslations[key] ?? normalizedAdditional[key] ?? text;
}

export const getLanguage = () => currentLanguage;

const LanguageContext = createContext<{
  language: Language;
  toggleLanguage: () => void;
}>({ language: currentLanguage, toggleLanguage: () => {} });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(currentLanguage);
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo(
    () => ({
      language,
      toggleLanguage: () => {
        const next = language === 'fr' ? 'en' : 'fr';
        currentLanguage = next;
        setLanguage(next);
        try {
          localStorage.setItem(LANGUAGE_KEY, next);
        } catch {
          // Language preference remains active for the current session.
        }
      },
    }),
    [language],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export const useLanguage = () => useContext(LanguageContext);
